"""Interfaces the use cases depend on. Infrastructure provides the implementations."""

from collections.abc import Callable, Sequence
from contextlib import AbstractContextManager
from datetime import datetime, timedelta
from types import TracebackType
from typing import TYPE_CHECKING, Protocol, Self

if TYPE_CHECKING:
    from readyreply.application.context import Actor

from readyreply.domain.ai import SuggestionResult
from readyreply.domain.answers import Answer, AnswerDraft
from readyreply.domain.search.index import SearchIndex
from readyreply.domain.sessions import Session
from readyreply.domain.synonyms import SynonymGroup
from readyreply.domain.unanswered import UnansweredQuestion
from readyreply.domain.users import User
from readyreply.domain.variables import Variable


class BusinessRepository(Protocol):
    def ensure(self, business_id: int, locale: str) -> bool:
        """Create the business if missing. Returns True when it was created."""
        ...

    def revision(self, business_id: int) -> int: ...
    def bump_revision(self, business_id: int) -> None: ...


class AnswerRepository(Protocol):
    def get(self, business_id: int, answer_id: int) -> Answer: ...
    def list_all(self, business_id: int) -> list[Answer]: ...
    def count(self, business_id: int) -> int: ...
    def add(self, answer: Answer) -> Answer: ...
    def update(self, answer: Answer) -> None: ...
    def delete(self, business_id: int, answer_id: int) -> None: ...
    def delete_all(self, business_id: int) -> None: ...
    def title_keys(self, business_id: int) -> frozenset[str]: ...
    def title_taken(self, business_id: int, key: str, exclude_id: int | None) -> bool: ...


class VariableRepository(Protocol):
    def list_all(self, business_id: int) -> list[Variable]: ...
    def replace_all(self, business_id: int, variables: Sequence[Variable]) -> None: ...


class SynonymRepository(Protocol):
    def list_all(self, business_id: int) -> list[SynonymGroup]: ...
    def replace_all(self, business_id: int, groups: Sequence[SynonymGroup]) -> None: ...


class UnansweredRepository(Protocol):
    def record(self, business_id: int, key: str, sample: str, now: datetime) -> None:
        """Insert the question or atomically add one to its counter."""
        ...

    def list_open(self, business_id: int, limit: int) -> list[UnansweredQuestion]: ...
    def get_open(self, business_id: int, question_id: int) -> UnansweredQuestion: ...
    def resolve(self, business_id: int, question_id: int, answer_id: int) -> None: ...
    def delete(self, business_id: int, question_id: int) -> None: ...


class CopyEventRepository(Protocol):
    def add(self, business_id: int, answer_id: int, user_id: int, now: datetime) -> None: ...
    def counts(self, business_id: int) -> dict[int, int]: ...


class UserRepository(Protocol):
    def any_exists(self) -> bool: ...
    def get(self, business_id: int, user_id: int) -> User: ...
    def find_by_username(self, business_id: int, username: str) -> User | None: ...
    def list_all(self, business_id: int) -> list[User]: ...
    def add(self, user: User) -> User: ...
    def update(self, user: User) -> None: ...
    def delete(self, business_id: int, user_id: int) -> None: ...


class SessionRepository(Protocol):
    def add(self, session: Session) -> None: ...
    def get(self, token_hash: str) -> Session | None: ...
    def update(self, session: Session) -> None: ...
    def delete(self, token_hash: str) -> None: ...
    def delete_for_user(self, user_id: int) -> None: ...
    def delete_expired(self, now: datetime) -> None: ...


class UnitOfWork(Protocol):
    """One transaction. Changes are kept only if `commit()` is called."""

    businesses: BusinessRepository
    answers: AnswerRepository
    variables: VariableRepository
    synonyms: SynonymRepository
    unanswered: UnansweredRepository
    copies: CopyEventRepository
    users: UserRepository
    sessions: SessionRepository

    def commit(self) -> None: ...
    def savepoint(self) -> AbstractContextManager[None]:
        """A nested transaction: an error inside rolls back only that part."""
        ...

    def __enter__(self) -> Self: ...
    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        traceback: TracebackType | None,
    ) -> None: ...


UnitOfWorkFactory = Callable[[], UnitOfWork]


class Clock(Protocol):
    def now(self) -> datetime: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password_hash: str, password: str) -> bool: ...


class TokenService(Protocol):
    def new_token(self) -> str: ...
    def hash_token(self, token: str) -> str: ...


class BusinessResolver(Protocol):
    """Which business the request belongs to (v1: always the single local business)."""

    def current(self) -> int: ...


class NetworkInfo(Protocol):
    def local_address(self) -> str: ...
    def qr_svg(self, text: str) -> bytes: ...


class RepeatGuard(Protocol):
    """Remembers recent actions to ignore double clicks."""

    def is_repeat(self, key: str, now: datetime, window: timedelta) -> bool: ...


class LoginFailureLog(Protocol):
    def record(self, key: str, now: datetime) -> None: ...
    def recent(self, key: str) -> list[datetime]: ...
    def clear(self, key: str) -> None: ...


class ProviderUnavailableError(Exception):
    """The AI provider could not produce a suggestion (not running, timeout, bad reply)."""


class SuggestionProvider(Protocol):
    def suggest(self, prompt: str) -> SuggestionResult: ...


CsvRow = tuple[int, dict[str, str]]
"""The file line where the row starts, and its cells by column name."""


class CsvCodec(Protocol):
    def decode(self, data: bytes) -> tuple[list[str], list[CsvRow]]:
        """Header and rows. Raises InvalidInputError for bad encoding or empty files."""
        ...

    def encode(self, header: Sequence[str], rows: Sequence[Sequence[str]]) -> bytes: ...


class AnswerWriter(Protocol):
    """Adds an answer inside a transaction the caller owns (and later commits)."""

    def add_within(self, uow: UnitOfWork, actor: "Actor", draft: AnswerDraft) -> Answer: ...


class SearchIndexProvider(Protocol):
    def get(self, uow: UnitOfWork, business_id: int) -> tuple[SearchIndex, dict[int, Answer]]: ...


class Texts(Protocol):
    """Server-side access to the translations file."""

    def text(self, key: str) -> str: ...
